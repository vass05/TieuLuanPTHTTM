"""Package verified notebook artifacts for the local Flask project (no training)."""
from pathlib import Path
import ast
import hashlib
import importlib
import json
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')


def export():
    import joblib
    import numpy as np
    import pandas as pd
    import torch
    from mvc.models.artifact_utils import artifact_digest

    source = ROOT / 'reports/chapter6/artifacts'
    hashes = {name.replace('\\', '/'): value for name, value in
              json.loads((source / 'artifact_hashes.json').read_text(encoding='utf-8')).items()}
    for name in ['pima_mlp_state.pt', 'pima_preprocessor.joblib', 'pima_model_metadata.json',
                 'knowledge_index.joblib', 'knowledge_graph.json', 'q_table_seed_11.npy']:
        actual = hashlib.sha256((source / name).read_bytes()).hexdigest()
        if actual != hashes['artifacts/' + name]:
            raise ValueError(f'Notebook artifact checksum mismatch: {name}')

    nb = json.loads((ROOT / 'TieuLuan_HeThongThongMinh.ipynb').read_text(encoding='utf-8'))
    definitions = {}
    required = ['Ch6MLP', 'ch6_mlp_proba', 'ch6_normalize', 'Ch6KnowledgeAgent',
                'ch6_encode_state', 'ch6_valid_actions', 'ch6_rule_policy', 'ch6_q_policy',
                'Ch6PredictionAgent', 'Ch6SafetyAgent']
    for cell in nb['cells']:
        if cell['cell_type'] != 'code' or 'chapter6' not in cell.get('metadata', {}).get('tags', []):
            continue
        text = ''.join(cell['source'])
        for node in ast.parse(text).body:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in required:
                definitions[node.name] = ast.get_source_segment(text, node)
    if set(definitions) != set(required):
        raise ValueError('Missing Chapter 6 definitions; export requires the completed notebook.')

    meta = json.loads((source / 'pima_model_metadata.json').read_text(encoding='utf-8'))
    # Bind source documents to an instance rather than a notebook-global variable.
    safety = definitions['Ch6SafetyAgent']
    safety = safety.replace('class Ch6SafetyAgent:\n',
        'class Ch6SafetyAgent:\n    def __init__(self, documents):\n'
        "        self.doc_by_id = {d['doc_id']: d for d in documents}\n\n", 1)
    safety = safety.replace('ch6_doc_by_id', 'self.doc_by_id')
    definitions['Ch6SafetyAgent'] = safety
    header = '''"""Notebook inference primitives; generated by scripts/export_chapter6_project.py.

Do not train at import. Regenerate from Chapter 6 when the experiment changes.
Safety document lookup is instance-bound for independent Flask app instances.
"""
import unicodedata
import numpy as np
import pandas as pd
import torch
from torch import nn
import networkx as nx
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import Normalizer
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.decomposition import TruncatedSVD

'''
    header += 'CH6_FEATURES = ' + repr(meta['features']) + '\n'
    header += 'CH6_ZERO_MISSING = ' + repr(meta['zero_as_missing']) + '\n'
    header += 'CH6_UNITS = ' + repr(meta['units']) + '\n'
    header += "CH6_ACTIONS = ['REQUEST_INFO', 'RUN_PREDICTION', 'RETRIEVE_KNOWLEDGE', 'GENERATE_RESPONSE', 'ESCALATE']\n"
    header += 'CH6_REQUEST, CH6_PREDICT, CH6_RETRIEVE, CH6_RESPOND, CH6_ESCALATE = range(5)\n\n'
    core_path = ROOT / 'mvc/models/chapter6_core.py'
    core_path.write_text(header + '\n\n'.join(definitions[name] for name in required) + '\n', encoding='utf-8')
    importlib.invalidate_caches()
    core = importlib.import_module('mvc.models.chapter6_core')

    diabetes = ROOT / 'model/diabetes'
    agents = ROOT / 'model/agents'
    diabetes.mkdir(parents=True, exist_ok=True)
    agents.mkdir(parents=True, exist_ok=True)
    for name in ['pima_mlp_state.pt', 'pima_preprocessor.joblib', 'pima_model_metadata.json']:
        shutil.copyfile(source / name, diabetes / name)
    shutil.copyfile(source / 'q_table_seed_11.npy', agents / 'q_table.npy')
    shutil.copyfile(source / 'knowledge_graph.json', agents / 'knowledge_graph.json')
    shutil.copyfile(ROOT / 'DATA/chapter6/knowledge_documents.json', agents / 'knowledge_documents.json')

    # A notebook pickle names its normalizer __main__.ch6_normalize. Resolve that
    # trusted local legacy symbol only during export, then persist a real module path.
    main_module = sys.modules['__main__']
    sentinel = object()
    previous = getattr(main_module, 'ch6_normalize', sentinel)
    setattr(main_module, 'ch6_normalize', core.ch6_normalize)
    try:
        index = joblib.load(source / 'knowledge_index.joblib')
    finally:
        if previous is sentinel:
            delattr(main_module, 'ch6_normalize')
        else:
            setattr(main_module, 'ch6_normalize', previous)
    index['vectorizer'].preprocessor = core.ch6_normalize
    joblib.dump(index, agents / 'knowledge_index.joblib')

    model = core.Ch6MLP()
    model.load_state_dict(torch.load(diabetes / 'pima_mlp_state.pt', weights_only=True, map_location='cpu'))
    predictor = core.Ch6PredictionAgent(model, joblib.load(diabetes / 'pima_preprocessor.joblib'), meta['threshold'])
    q_table = np.load(agents / 'q_table.npy', allow_pickle=False)
    if q_table.shape != (32, 5) or not np.isfinite(q_table).all():
        raise ValueError('Invalid Q-table')

    data_path = ROOT / 'DATA/pima_indians_diabetes.csv'
    if hashlib.sha256(data_path.read_bytes()).hexdigest() != meta['dataset_sha256']:
        raise ValueError('Pima dataset checksum mismatch')
    data = pd.read_csv(data_path)
    split = json.loads((source / 'split_indices.json').read_text(encoding='utf-8'))
    complete = [i for i in split['test'] if (data.loc[i, meta['zero_as_missing']] > 0).all()]
    examples = []
    for i, row_id in enumerate(complete[:3]):
        profile = {key: float(data.loc[row_id, key]) for key in meta['features']}
        examples.append(dict(id=f'pima-{i+1}', name=f'Mẫu nghiên cứu {i+1}', profile=profile,
            query='A1C cho biết điều gì trong kế hoạch chăm sóc?',
            expected_prediction=predictor.predict(profile)))
    write_json(agents / 'examples.json', examples)
    environment = json.loads((source / 'environment.json').read_text(encoding='utf-8'))
    manifest = dict(format_version=1, model_version='pima-mlp-chapter6-v1',
        q_seed=11, q_shape=[32, 5], inference_core_sha256=artifact_digest(core_path),
        digest_format='normalized-text-v1',
        source='reports/chapter6/artifacts', packages=environment['packages'],
        thresholds=index['thresholds'], files={})
    for folder in [diabetes, agents]:
        for path in sorted(folder.iterdir()):
            if path.is_file() and path.name != 'manifest.json':
                manifest['files'][path.relative_to(ROOT / 'model').as_posix()] = artifact_digest(path)
    write_json(agents / 'manifest.json', manifest)
    print('Exported model/diabetes and model/agents. No training or notebook edits.')


if __name__ == '__main__':
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
    export()
